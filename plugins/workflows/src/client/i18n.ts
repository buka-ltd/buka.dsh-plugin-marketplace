import type { Translate } from './types.ts'

/** 把词典里的 `{name}` 占位符换成值。 */
export function fill(t: Translate, key: string, values: Record<string, string | number>): string {
  let text = t(key)
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

